package com.dmitrylegend.apitranslator

import kotlin.math.abs

/**
 * Простые математические помощники. Здесь нет ничего из Android, поэтому
 * код из этого файла можно прогнать обычным тестом на компьютере
 * (app/src/test/.../GeomTest.kt) — без телефона и эмулятора.
 *
 * Все они нужны для одной вещи: объяснить разницу между двумя системами
 * координат.
 *
 * Телефон можно повернуть. Мы всегда снимаем картинку экрана в «родной»
 * ориентации — вертикально, как телефон лежит в кармане, даже если сейчас он
 * лежит на боку. А программа распознавания текста выдаёт координаты в
 * «выпрямленной» ориентации — как будто телефон стоит вертикально.
 *
 * Всё остальное приложение (и оверлей, на который смотрит человек) работает
 * в выпрямленных координатах. Значит, нам нужно уметь переводить одно в другое.
 */

/** Насколько экран повёрнут относительно «родного» положения телефона. */
const val ROT_0 = 0
const val ROT_90 = 90
const val ROT_180 = 180
const val ROT_270 = 270

/**
 * Сколько раз [fitSize] делит диапазон пополам, подбирая размер шрифта.
 * Диапазон от 6 до 100 пикселей после 10 делений сходится точнее, чем на
 * 0.1 пикселя. Для букв этого более чем достаточно — глаз разницу не видит.
 */
private const val FIT_STEPS = 10

/**
 * Переводит прямоугольник из выпрямленных координат в координаты картинки.
 *
 * Если телефон повёрнут, картинка внутри буфера лежит «боком» относительно
 * того, что видит человек. Здесь мы берём четыре угла прямоугольника,
 * пересчитываем их в координаты картинки и находим новые углы.
 *
 * Повороты кратны 90°, поэтому прямоугольник остаётся прямоугольником и
 * сложная математика не нужна — достаточно взять минимум и максимум.
 *
 * Возвращает `[лево, верх, право, низ]` в координатах картинки.
 *
 * `bw` и `bh` — размеры картинки, то есть экрана в «родной» ориентации.
 * После поворота они отличаются от размеров экрана на глазах.
 */
fun toBufferBox(left: Int, top: Int, right: Int, bottom: Int, deg: Int, bw: Int, bh: Int): IntArray {
    fun bx(ux: Int, uy: Int) = when (deg) {
        ROT_90 -> uy
        ROT_180 -> bw - 1 - ux
        ROT_270 -> bw - 1 - uy
        else -> ux
    }

    fun by(ux: Int, uy: Int) = when (deg) {
        ROT_90 -> bh - 1 - ux
        ROT_180 -> bh - 1 - uy
        ROT_270 -> ux
        else -> uy
    }

    val xs = intArrayOf(bx(left, top), bx(right, top), bx(left, bottom), bx(right, bottom))
    val ys = intArrayOf(by(left, top), by(right, top), by(left, bottom), by(right, bottom))
    return intArrayOf(xs.min(), ys.min(), xs.max(), ys.max())
}

/**
 * Подбирает размер шрифта: берёт наибольший из диапазона `[minSize, maxSize]`,
 * при котором текст влезает в высоту `maxHeight`.
 *
 * Функция `heightOf` должна выдавать бо́льшую высоту при бо́льшем размере
 * шрифта. Так и есть: чем крупнее буквы, тем больше строк нужно, и тем выше
 * текст. Благодаря этому можно перебирать размеры пополам, а не пробовать
 * все подряд.
 *
 * Если `maxSize` уже подходит — вернёт его. Если даже `minSize` великоват —
 * вернёт `minSize`. Тогда текст обрежется снизу, но мы предпочли бы показать
 * почти всё, чем не показать ничего: для субтитров это лучший вариант.
 */
fun fitSize(minSize: Float, maxSize: Float, maxHeight: Float, heightOf: (Float) -> Float): Float {
    if (maxSize <= minSize) return minSize
    if (heightOf(maxSize) <= maxHeight) return maxSize

    var lo = minSize
    var hi = maxSize
    repeat(FIT_STEPS) {
        val mid = (lo + hi) / 2f
        if (heightOf(mid) <= maxHeight) lo = mid else hi = mid
    }
    return lo
}

/**
 * Насколько две строки близки друг к другу.
 *
 * Распознавание текста дрожет: одну и ту же фразу кадр за кадром оно читает то
 * «Hello, world!», то «Неllo, wоrld!», то «Hello, world» без запятой. Если
 * искать перевод по точному совпадению, каждая такая описка будет считаться
 * новой строкой — экран мигает, а лимит DeepL уходит впустую.
 *
 * Возвращает true, если строки отличаются не более чем на [max] правок:
 * вставка, удаление или замена одного символа.
 *
 * Расстояние считается полосами: храним только две строки вместо всей
 * таблицы. Выходим раньше только когда даже лучшая позиция в строке уехала
 * за [max]: строка идёт слева направо, и опуститься ниже этого уже не
 * получится.
 */
fun editDistanceWithin(a: String, b: String, max: Int): Boolean {
    if (a == b) return true
    if (abs(a.length - b.length) > max) return false

    var previous = IntArray(b.length + 1) { it }
    var current = IntArray(b.length + 1)

    for (i in 1..a.length) {
        current[0] = i
        var best = current[0]
        for (j in 1..b.length) {
            val cost = if (a[i - 1] == b[j - 1]) 0 else 1
            current[j] = minOf(
                current[j - 1] + 1,      // вставка
                previous[j] + 1,        // удаление
                previous[j - 1] + cost, // замена
            )
            if (current[j] < best) best = current[j]
        }
        if (best > max) return false
        val swap = previous
        previous = current
        current = swap
    }
    return previous[b.length] <= max
}

/**
 * Точки по краю рамки вокруг найденного текста. По ним мы угадываем, какой
 * цвет у фона под этим текстом.
 *
 * Почему именно снаружи, а не внутри: внутри рамки находятся сами буквы.
 * Там смесь из чернил и фона, и медиана по ней скажет «текст тёмный», а не
 * «фон такого-то цвета». А вокруг рамки — почти чистый фон. Вот его цвет и
 * нужен: им мы закрасим оригинал.
 *
 * Возвращает простой список координат `[x0, y0, x1, y1, ...]` — без сортировки,
 * местами с повторами. Точки за пределами картинки вызывающая сторона
 * отбросит сама.
 */
fun ringPoints(left: Int, top: Int, right: Int, bottom: Int, band: Int): IntArray {
    val out = ArrayList<Int>((right - left + 1 + bottom - top + 1) * band * 2)
    // Полосы берём строго снаружи, начиная с i = 1. При i = 0 точки лёгли бы
    // прямо на границу рамки, а там уже сами буквы, и медиана посчитала бы
    // цвет текста вместо цвета фона.
    for (i in 1..band) {
        for (x in left..right) {
            out.add(x); out.add(top - i)      // тонкая полоска прямо над рамкой
            out.add(x); out.add(bottom + i)   // и прямо под ней
        }
    }
    for (i in 1..band) {
        for (y in top..bottom) {
            out.add(left - i); out.add(y)     // полоска слева
            out.add(right + i); out.add(y)    // полоска справа
        }
    }
    return out.toIntArray()
}

/**
 * Средний цвет по каждому каналу — медиана, а не среднее арифметическое.
 *
 * Разница наглядная: если среди точек есть один яркий пиксель (блик от
 * нажатия, курсор, артефакт сжатия видео), среднее арифметическое уползёт
 * в его сторону, а медиана его просто не заметит. Именно на этом различии
 * решается, будет ли заливка «в цвет фона» или серым пятном.
 */
fun medianColor(pixels: IntArray): Int {
    if (pixels.isEmpty()) return 0
    val r = IntArray(pixels.size)
    val g = IntArray(pixels.size)
    val b = IntArray(pixels.size)
    for (i in pixels.indices) {
        val c = pixels[i]
        r[i] = (c shr 16) and 0xFF
        g[i] = (c shr 8) and 0xFF
        b[i] = c and 0xFF
    }
    r.sort(); g.sort(); b.sort()
    val m = pixels.size / 2
    return (0xFF shl 24) or (r[m] shl 16) or (g[m] shl 8) or b[m]
}
